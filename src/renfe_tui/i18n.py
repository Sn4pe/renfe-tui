STRINGS = {"es": ES, "en": EN}


def detect() -> str:
    for name in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        value = os.environ.get(name, "")
        if value and value not in ("C", "POSIX"):
            return "es" if value.lower().startswith("es") else "en"
    found = locale.getlocale()[0] or ""
    return "es" if found.lower().startswith("es") else "en"


def set_language(lang: str | None) -> str:
    global _lang
    _lang = lang if lang in LANGS else detect()
    return _lang


def lang() -> str:
    return _lang


def t(key: str, **values):
    text = STRINGS[_lang][key]
    return text.format(**values) if values else text
